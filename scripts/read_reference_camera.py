"""Read an active camera from a saved workflow .blend, without modifying it."""
import argparse
import json
from pathlib import Path
import sys
import bpy
import numpy as np

p = argparse.ArgumentParser()
p.add_argument('--output', required=True)
a = p.parse_args(sys.argv[sys.argv.index('--')+1:])
s = bpy.context.scene
c = s.camera
if c is None or c.data.type != 'PERSP':
    raise ValueError('The reference .blend must have an active perspective camera.')
meshes = [o for o in s.objects if o.type == 'MESH' and len(o.data.vertices) > 10]
if not meshes:
    raise ValueError('No depth mesh or UniSHARP points found in reference file.')
obj = max(meshes, key=lambda o: len(o.data.vertices))
if c.data.sensor_fit != 'HORIZONTAL':
    raise ValueError('Use a .blend generated by this workflow (horizontal sensor fit).')
v = np.empty(len(obj.data.vertices)*3, np.float32)
obj.data.vertices.foreach_get('co', v)
z = v.reshape(-1, 3)[:, 2]
z = z[np.isfinite(z) & (z > 0)]
if not len(z):
    raise ValueError('Reference mesh does not use the workflow camera-space axes.')
source = bpy.data.objects.get('01 Original photo camera')
projection = source.data if source and source.type == 'CAMERA' else c.data
data = {
    'camera_name': c.name, 'matrix': [list(row) for row in c.matrix_world],
    'axes': [list(row) for row in obj.matrix_world], 'median_z': float(np.median(z)),
    'lens': projection.lens, 'sensor_width': projection.sensor_width,
    'shift': [projection.shift_x, projection.shift_y],
    'target_lens': c.data.lens, 'target_sensor_width': c.data.sensor_width,
    'target_shift': [c.data.shift_x, c.data.shift_y],
    'pixel_aspect': s.render.pixel_aspect_y/s.render.pixel_aspect_x,
    'aspect': s.render.resolution_x/s.render.resolution_y,
    'note': 'Saved file state only; camera is not live-linked. Mesh aligned by median local depth.'
}
Path(a.output).write_text(json.dumps(data, indent=2), encoding='utf-8')
print('Reference camera read:', c.name)
